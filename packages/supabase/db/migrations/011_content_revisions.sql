-- The saved versions of content items, for History in the edit form (the content-model skill of
-- @plutocms/core, "Revisions"). The content adapter of this layer writes one row after each create
-- and update, with the client of the signed-in user. Every content type of every layer shares this
-- table. Every statement is idempotent.

create table if not exists public.pluto_content_revisions (
  id          bigint generated by default as identity not null,
  created_at  timestamp with time zone not null default now(),
  type        text not null,                -- the content type name
  item_id     text not null,                -- the primary key of the item, as text
  action      text null,                    -- create, update, publish or unpublish
  data        jsonb not null,               -- the item after the save, by field name
  author_id   uuid null default auth.uid() references auth.users (id) on delete set null,
  author_name text null,                    -- the name at save time
  capability  text null,                    -- the write capability of the type at save time
  constraint pluto_content_revisions_pkey primary key (id),
  constraint pluto_content_revisions_action_check check (
    action is null or action in ('create', 'update', 'publish', 'unpublish', 'rename')
  )
);

create index if not exists pluto_content_revisions_item_idx
  on public.pluto_content_revisions (type, item_id, id desc);

alter table public.pluto_content_revisions enable row level security;

-- An editor of the type: the stored write capability, or any staff capability for a type with
-- none. public.has_capability() folds in public.is_admin().
drop policy if exists "pluto_content_revisions_select" on public.pluto_content_revisions;
create policy "pluto_content_revisions_select"
  on public.pluto_content_revisions for select
  to authenticated
  using (
    (capability is null and exists (select 1 from public.my_capabilities()))
    or public.has_capability(capability)
  );

drop policy if exists "pluto_content_revisions_insert" on public.pluto_content_revisions;
create policy "pluto_content_revisions_insert"
  on public.pluto_content_revisions for insert
  to authenticated
  with check (
    author_id = auth.uid()
    and (
      (capability is null and exists (select 1 from public.my_capabilities()))
      or public.has_capability(capability)
    )
  );

drop policy if exists "pluto_content_revisions_delete" on public.pluto_content_revisions;
create policy "pluto_content_revisions_delete"
  on public.pluto_content_revisions for delete
  to authenticated
  using (
    (capability is null and exists (select 1 from public.my_capabilities()))
    or public.has_capability(capability)
  );

grant select, insert, delete on public.pluto_content_revisions to authenticated;
grant select, insert, update, delete on public.pluto_content_revisions to service_role;
