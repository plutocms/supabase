-- The server copy of the unsaved changes of an editor (the content-backup skill of
-- @plutocms/core). The edit form sends the copy while the editor types, so the editor can pick the
-- changes up again on another device. One row for each user, content type and item. Only the owner
-- reads or writes a row. Every content type of every layer shares this table. Every statement is
-- idempotent.

create table if not exists public.pluto_content_backups (
  id          bigint generated by default as identity not null,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  type        text not null,                -- the content type name
  item_key    text not null,                -- the item id as text, '+new' for a new item
  device      text not null,                -- the device id of the record
  saved_at    timestamp with time zone not null,  -- savedAt of the record (the browser clock)
  updated_at  timestamp with time zone not null default now(),  -- the server time of the write
  record      jsonb not null,
  constraint pluto_content_backups_pkey primary key (id),
  constraint pluto_content_backups_item_key unique (user_id, type, item_key),
  constraint pluto_content_backups_item_key_length check (char_length(item_key) between 1 and 500),
  constraint pluto_content_backups_record_size check (octet_length(record::text) <= 5000000)
);

create index if not exists pluto_content_backups_user_idx
  on public.pluto_content_backups (user_id, updated_at desc);

alter table public.pluto_content_backups enable row level security;

-- Owner only. The core route checks the write capability of the type, and a row only ever shows
-- its owner their own data, so the policies hold no capability.
drop policy if exists "pluto_content_backups_select" on public.pluto_content_backups;
create policy "pluto_content_backups_select"
  on public.pluto_content_backups for select
  to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "pluto_content_backups_insert" on public.pluto_content_backups;
create policy "pluto_content_backups_insert"
  on public.pluto_content_backups for insert
  to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists "pluto_content_backups_update" on public.pluto_content_backups;
create policy "pluto_content_backups_update"
  on public.pluto_content_backups for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "pluto_content_backups_delete" on public.pluto_content_backups;
create policy "pluto_content_backups_delete"
  on public.pluto_content_backups for delete
  to authenticated
  using (user_id = (select auth.uid()));

grant select, insert, update, delete on public.pluto_content_backups to authenticated;
grant select, insert, update, delete on public.pluto_content_backups to service_role;
