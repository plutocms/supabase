-- The media library of core (the media skill of @plutocms/pluto), on Supabase.
-- The table and the bucket were in @plutocms/supabase-storage, which retires.
-- Every statement is idempotent, so a database with the old storage layer and a
-- new database get the same result.

create table if not exists public.media (
  id           bigint generated by default as identity not null,
  created_at   timestamp with time zone not null default now(),
  name         character varying null,  -- the original file name, for people
  alt          character varying null,
  storage_path character varying null,  -- the object key in `bucket`
  mime_type    character varying null,
  size         bigint null,             -- in bytes
  constraint media_pkey primary key (id)
);

-- The bucket of each file. New files go to `media`. Older files can stay in
-- another bucket (the shop's `product-media`), so no bytes move.
alter table public.media add column if not exists bucket text not null default 'media';
alter table public.media add column if not exists width integer null;
alter table public.media add column if not exists height integer null;

create index if not exists media_created_at_idx on public.media (created_at desc);

alter table public.media enable row level security;

drop policy if exists "media_select_public" on public.media;
create policy "media_select_public"
  on public.media for select
  using (true);

drop policy if exists "media_insert_authenticated" on public.media;
create policy "media_insert_authenticated"
  on public.media for insert
  with check (public.has_capability('media:manage'));

drop policy if exists "media_update_authenticated" on public.media;
create policy "media_update_authenticated"
  on public.media for update
  using (public.has_capability('media:manage'))
  with check (public.has_capability('media:manage'));

drop policy if exists "media_delete_authenticated" on public.media;
create policy "media_delete_authenticated"
  on public.media for delete
  using (public.has_capability('media:delete'));

grant select on public.media to anon;
grant select, insert, update, delete on public.media to authenticated;
grant select, insert, update, delete on public.media to service_role;

-- The bucket: public read. A file name never changes, so it can be cached for ever.
insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do nothing;

drop policy if exists "media: public read" on storage.objects;
create policy "media: public read"
  on storage.objects for select
  using (bucket_id = 'media');

drop policy if exists "media: admin insert" on storage.objects;
create policy "media: admin insert"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'media' and public.has_capability('media:manage'));

drop policy if exists "media: admin update" on storage.objects;
create policy "media: admin update"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'media' and public.has_capability('media:manage'))
  with check (bucket_id = 'media' and public.has_capability('media:manage'));

drop policy if exists "media: admin delete" on storage.objects;
create policy "media: admin delete"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'media' and public.has_capability('media:delete'));

-- Older rows: the type and the size from the stored object. A 3D model often
-- has no real type in Storage, so `.glb` gets its type from the name.
update public.media m
set
  mime_type = coalesce(m.mime_type, nullif(o.metadata ->> 'mimetype', 'application/octet-stream')),
  size = coalesce(m.size, (o.metadata ->> 'size')::bigint)
from storage.objects o
where o.bucket_id = m.bucket
  and o.name = m.storage_path
  and (m.mime_type is null or m.size is null);

update public.media
set mime_type = 'model/gltf-binary'
where storage_path ilike '%.glb'
  and mime_type is distinct from 'model/gltf-binary';
